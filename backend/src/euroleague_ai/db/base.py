"""Declarative base and shared type conventions.

Importing :data:`Base` alone is not enough for Alembic autogeneration -- the
model modules must also have been imported so their tables register on the
metadata. ``euroleague_ai.models`` does that, and ``migrations/env.py`` imports
it for exactly that reason.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, MetaData
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase

# Explicit naming conventions so Alembic emits stable, predictable constraint
# names. Without this, autogenerated downgrades cannot reliably drop unnamed
# constraints and migrations become one-way.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every ORM model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Every datetime column in this schema is timezone-aware. Enforcing it here
    # means no individual model can forget and introduce a naive column, which
    # would break time-ordered comparisons in ways that are painful to detect.
    type_annotation_map = {
        datetime: DateTime(timezone=True),
        dict[str, Any]: JSONB,
        list[str]: JSONB,
    }

    def __repr__(self) -> str:
        pk = getattr(self, "id", None)
        return f"<{type(self).__name__} id={pk}>"
